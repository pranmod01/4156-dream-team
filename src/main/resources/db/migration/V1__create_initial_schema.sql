CREATE TABLE organization (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_name      VARCHAR(255) NOT NULL UNIQUE,
    api_key_hash  VARCHAR(64)  NOT NULL UNIQUE,
    max_cpus      INTEGER NOT NULL CHECK (max_cpus >= 0),
    max_gpus      INTEGER NOT NULL CHECK (max_gpus >= 0),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE resource (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  BIGINT NOT NULL REFERENCES organization(id),
    resource_type    VARCHAR(10) NOT NULL CHECK (resource_type IN ('CPU', 'GPU')),
    memory_gb        INTEGER NOT NULL CHECK (memory_gb > 0),
    cores            INTEGER CHECK (cores > 0),
    is_online        BOOLEAN NOT NULL DEFAULT TRUE,
    CHECK ((resource_type = 'CPU' AND cores IS NOT NULL) OR (resource_type = 'GPU' AND cores IS NULL))
);

CREATE TABLE job (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id     BIGINT NOT NULL REFERENCES organization(id),
    resource_type       VARCHAR(10) NOT NULL CHECK (resource_type IN ('CPU', 'GPU')),
    units_requested     INTEGER NOT NULL CHECK (units_requested > 0),
    min_memory_gb       INTEGER NOT NULL CHECK (min_memory_gb > 0),
    min_cores           INTEGER CHECK (min_cores > 0),
    max_duration_hours  INTEGER NOT NULL CHECK (max_duration_hours > 0),
    job_status          VARCHAR(10) NOT NULL DEFAULT 'QUEUED'
                        CHECK (job_status IN ('QUEUED', 'RUNNING', 'DONE')),
    submitted_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at          TIMESTAMP WITH TIME ZONE,
    lease_end           TIMESTAMP WITH TIME ZONE,
    CHECK ((resource_type = 'CPU' AND min_cores IS NOT NULL)
        OR (resource_type = 'GPU' AND min_cores IS NULL))
);

CREATE TABLE job_resource (
    job_id       BIGINT NOT NULL REFERENCES job(id) ON DELETE CASCADE,
    resource_id  BIGINT NOT NULL REFERENCES resource(id),
    PRIMARY KEY (job_id, resource_id)
);

CREATE INDEX idx_job_queue ON job (organization_id, job_status, submitted_at);
CREATE INDEX idx_job_resource_resource ON job_resource (resource_id);
